/**
 * Generates `src/generated/wordmark.ts` — the brand wordmark as real vector paths, set in
 * Instrument Sans Bold (SIL Open Font License) with tight tracking.
 *
 * Why paths instead of live text? The hero uses the wordmark as a CSS mask-image and draws its
 * outline with DrawSVG; both need path geometry, and data-URL SVGs cannot load web fonts.
 *
 * Usage:  node scripts/generate-wordmark.mjs            (reads brand.name from src/content/site.ts)
 *         node scripts/generate-wordmark.mjs "ACME"     (explicit text)
 * Runs automatically before `npm run dev` / `npm run build` (see package.json "predev"/"prebuild").
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fontFile = path.join(root, "scripts/fonts/InstrumentSans-Bold.ttf");
const outFile = path.join(root, "src/generated/wordmark.ts");

function brandNameFromContent() {
  try {
    const src = fs.readFileSync(path.join(root, "src/content/site.ts"), "utf8");
    const m = src.match(/brand:\s*\{[\s\S]*?name:\s*"([^"]+)"/);
    return m?.[1];
  } catch {
    return undefined;
  }
}

const text = process.argv[2] || brandNameFromContent() || "HAVEN";
const fontBuf = fs.readFileSync(fontFile);
const font = opentype.parse(fontBuf.buffer.slice(fontBuf.byteOffset, fontBuf.byteOffset + fontBuf.byteLength));

const fontSize = 1000; // units; viewBox is normalized to the glyph bounds below
const tracking = -0.045; // em — tight display tracking, like the site's headings
const glyphPaths = [];
let x = 0;
// Map characters straight to glyphs (skips GSUB feature lookups that opentype.js cannot parse in this font).
const glyphs = [...text].map((ch) => font.charToGlyph(ch));
const full = new opentype.Path();
glyphs.forEach((glyph, i) => {
  const p = glyph.getPath(x, 0, fontSize);
  glyphPaths.push({ char: text[i], d: p.toPathData(2), bbox: p.getBoundingBox() });
  full.extend(p);
  let advance = (glyph.advanceWidth / font.unitsPerEm) * fontSize;
  if (i < glyphs.length - 1) {
    const kern = font.getKerningValue(glyph, glyphs[i + 1]) || 0;
    advance += (kern / font.unitsPerEm) * fontSize + tracking * fontSize;
  }
  x += advance;
});

const bb = full.getBoundingBox();
const pad = 4;
const viewBox = [bb.x1 - pad, bb.y1 - pad, bb.x2 - bb.x1 + pad * 2, bb.y2 - bb.y1 + pad * 2].map((n) => +n.toFixed(2));

const out = `/* AUTO-GENERATED by scripts/generate-wordmark.mjs — do not edit by hand.
 * Regenerate after changing brand.name in src/content/site.ts: \`node scripts/generate-wordmark.mjs\`
 */
export const wordmark = {
  text: ${JSON.stringify(text)},
  /** viewBox = "minX minY width height" — the path is NOT normalized to 0,0 */
  viewBox: ${JSON.stringify(viewBox.join(" "))},
  width: ${viewBox[2]},
  height: ${viewBox[3]},
  /** Whole word as one compound path (use for masks and stroke draw-on) */
  d: ${JSON.stringify(full.toPathData(2))},
  /** Per-letter paths (use for staggered reveals) */
  letters: ${JSON.stringify(glyphPaths.map((g) => ({ char: g.char, d: g.d })))},
} as const;

/** Data URL usable directly in CSS: mask-image: url(WORDMARK_MASK_URL) */
export const WORDMARK_MASK_URL = \`data:image/svg+xml,\${encodeURIComponent(
  \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="\${wordmark.viewBox}"><path fill="black" d="\${wordmark.d}"/></svg>\`,
)}\`;
`;

// Favicon: first letter of the brand on a dark rounded tile (src/app/icon.svg is picked up by Next automatically).
{
  const g = glyphPaths[0];
  const bw = g.bbox.x2 - g.bbox.x1, bh = g.bbox.y2 - g.bbox.y1;
  const size = 64, inner = 36;
  const sc = inner / Math.max(bw, bh);
  const tx = (size - bw * sc) / 2 - g.bbox.x1 * sc;
  const ty = (size - bh * sc) / 2 - g.bbox.y1 * sc;
  const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" rx="14" fill="#151717"/><path transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${sc.toFixed(5)})" fill="#fff" d="${g.d}"/></svg>
`;
  fs.writeFileSync(path.join(root, "src/app/icon.svg"), icon);
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(`wordmark "${text}" → ${path.relative(root, outFile)} (viewBox ${viewBox.join(" ")})`);
